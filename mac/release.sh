#!/bin/zsh
# Build a release of TimeLock for Mac: universal (Apple Silicon + Intel) app
# with an installer, written to ../updates/mac/TimeLock-Mac.zip + latest.json.
# Usually run by .github/workflows/mac-release.yml when mac/VERSION changes on
# main. Notes come from RELEASE_NOTES.txt (or UPDATE_NOTES="…").
set -e
cd "$(dirname "$0")"
VERSION=$(cat VERSION)
# Every error code used in the app and installer must be on the public error list.
missing=$(grep -ohE 'TL-[0-9]{3}' Sources/TimeLock/*.swift release.sh | sort -u | while read -r c; do
  grep -q "^| \`$c\` |" ../ERRORS.md || echo "$c"
done)
if [[ -n "$missing" ]]; then
  echo "Error codes missing from ERRORS.md: $missing" >&2
  exit 1
fi
if [[ -z "${UPDATE_NOTES:-}" && -f RELEASE_NOTES.txt ]]; then
  UPDATE_NOTES=$(<RELEASE_NOTES.txt)
fi
BUILT=$(date "+%b %d, %H:%M")
FEED="${UPDATE_FEED-https://raw.githubusercontent.com/jonpikereally/TimeLock/main/updates/mac/latest.json}"
cat > Sources/TimeLock/Version.swift <<SWIFT
// Generated by build.sh / release.sh — do not edit.
enum AppVersion {
    static let version = "$VERSION"
    static let built = "$BUILT"
    static let updateFeed = "$FEED"
}
SWIFT
CACHE="${TMPDIR:-/tmp}/timelock-modcache"
mkdir -p "$CACHE"
echo "Building arm64…"
swiftc -O -target arm64-apple-macos13 -module-cache-path "$CACHE" \
  -o "$CACHE/TimeLock-arm64" Sources/TimeLock/*.swift
echo "Building x86_64…"
swiftc -O -target x86_64-apple-macos13 -module-cache-path "$CACHE-x86" \
  -o "$CACHE/TimeLock-x86_64" Sources/TimeLock/*.swift

DIST="$CACHE/dist"
rm -rf "$DIST"
APP="$DIST/TimeLock/TimeLock.app"
mkdir -p "$APP/Contents/MacOS"
lipo -create -output "$APP/Contents/MacOS/TimeLock" \
  "$CACHE/TimeLock-arm64" "$CACHE/TimeLock-x86_64"
cp Resources/Info.plist "$APP/Contents/Info.plist"
mkdir -p "$APP/Contents/Resources"
cp Resources/AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"
/usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $VERSION" "$APP/Contents/Info.plist"
codesign --force --sign - "$APP"

cat > "$DIST/TimeLock/Install TimeLock.command" <<'INSTALL'
#!/bin/bash
# TimeLock installer — copies the app to ~/Applications and launches it.
cd "$(dirname "$0")"
fail() {
  echo
  echo "Error $1: $2"
  echo "Look up this code on the TimeLock error list:"
  echo "  https://github.com/jonpikereally/TimeLock/blob/main/ERRORS.md"
  echo "(You can also give that page to an AI assistant for help.)"
  exit 1
}
echo "Installing TimeLock…"
mkdir -p ~/Applications || fail TL-801 "Couldn't create ~/Applications."
osascript -e 'quit app id "com.jonpike.timelock"' 2>/dev/null
rm -rf ~/Applications/TimeLock.app
ditto --norsrc TimeLock.app ~/Applications/TimeLock.app \
  || fail TL-801 "Couldn't copy TimeLock into ~/Applications."
# Clear the download quarantine and re-sign locally so macOS trusts it on this Mac.
xattr -dr com.apple.quarantine ~/Applications/TimeLock.app 2>/dev/null
codesign --force --sign - ~/Applications/TimeLock.app 2>/dev/null \
  || fail TL-802 "Couldn't sign TimeLock for this Mac."
open ~/Applications/TimeLock.app \
  || fail TL-803 "TimeLock was installed but couldn't be opened. Open it from ~/Applications yourself."
echo
echo "Done! Look for the hourglass in your menu bar."
echo "If the TimeLock browser extension is installed, reload it once so it connects."
INSTALL
chmod +x "$DIST/TimeLock/Install TimeLock.command"

cat > "$DIST/TimeLock/README.txt" <<README
TimeLock for Mac v$VERSION — tracks your time in apps (macOS 13+)
https://github.com/jonpikereally/TimeLock

INSTALL
1. Double-click "Install TimeLock.command".
   If macOS blocks it: right-click it, choose Open, then Open again.
2. Look for the hourglass in the menu bar. TimeLock needs no permissions.

WHAT IT DOES
• Counts time in the app you're using. Pauses after a minute with no mouse
  or keyboard input (unless a video is playing) and when the screen locks.
• Works with the TimeLock browser extension: your app time shows in the
  extension, a daily limit can include apps (e.g. "Social: x.com + Discord"),
  and this menu shows your website time and limits. Apps are never locked;
  when a limit runs out, its websites lock.

PRIVACY
Everything stays on your Mac (~/Library/Application Support/TimeLock).
No accounts, no analytics. The only thing TimeLock fetches from the internet
is a small version file from the GitHub repo above, to check for updates.
README

OUT=../updates/mac
mkdir -p "$OUT"
(cd "$DIST" && ditto -c -k --norsrc --noextattr --noqtn --keepParent TimeLock "$OLDPWD/$OUT/TimeLock-Mac.zip.tmp")
mv -f "$OUT/TimeLock-Mac.zip.tmp" "$OUT/TimeLock-Mac.zip"
# Manifest last, so a checking app never sees it pointing at a half-written zip.
/usr/bin/python3 -c 'import json,sys; print(json.dumps({"version": sys.argv[1], "url": "TimeLock-Mac.zip", "notes": sys.argv[2]}))' \
  "$VERSION" "${UPDATE_NOTES:-}" > "$OUT/latest.json.tmp"
mv -f "$OUT/latest.json.tmp" "$OUT/latest.json"
echo "Release v$VERSION written to updates/mac/."
